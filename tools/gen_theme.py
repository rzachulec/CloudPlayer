#!/usr/bin/env python3
"""Generates CloudPlayer/ThemeVars.swift from SoundCloud's stylesheet.

SoundCloud themes everything through CSS custom properties defined on `.theme-light,:root`
and `.theme-dark`. This remaps every variable whose value is one of SoundCloud's palette
colours onto a handful of `--cp-*` tokens, which the app fills with real macOS system
colours (see Theme.swift). Re-run when SoundCloud ships new CSS:

    python3 tools/gen_theme.py <url-or-path-of-app-*.css>

The current app CSS URL is in the page's <link rel="stylesheet"> (a-v2.sndcdn.com/assets/css/app-*.css).
"""
import re
import sys
import urllib.request
from pathlib import Path

# SoundCloud palette value -> cp token, per theme.
DARK = {"#121212": "bg", "#fff": "label", "#999": "secondary", "#303030": "fill",
        "#699fff": "link", "#f50": "accent"}
LIGHT = {"#fff": "bg", "#121212": "label", "#666": "secondary", "#f3f3f3": "fill",
         "#044dd2": "link", "#f50": "accent"}
SHARED = {"#f50": "accent"}

RGB = {"18,18,18": "#121212", "255,255,255": "#fff", "153,153,153": "#999", "102,102,102": "#666",
       "48,48,48": "#303030", "243,243,243": "#f3f3f3", "105,159,255": "#699fff",
       "4,77,210": "#044dd2", "255,85,0": "#f50"}

# Variables that are meant to be absolute colours regardless of theme.
ABSOLUTE = re.compile(r"(light|dark|white|black)")


def remap(value, palette):
    v = value.strip().lower()
    if v in palette:
        return f"var(--cp-{palette[v]})"
    m = re.fullmatch(r"(\d+,\d+,\d+)", v.replace(" ", ""))
    if m and RGB.get(m.group(1)) in palette:
        return f"var(--cp-{palette[RGB[m.group(1)]]}-rgb)"
    m = re.fullmatch(r"rgba\((\d+,\d+,\d+),([\d.]+)\)", v.replace(" ", ""))
    if m and RGB.get(m.group(1)) in palette:
        return f"rgba(var(--cp-{palette[RGB[m.group(1)]]}-rgb),{m.group(2)})"
    m = re.fullmatch(r"hsla\(0,0%,100%,([\d.]+)\)", v.replace(" ", ""))
    if m and "#fff" in palette:
        return f"rgba(var(--cp-{palette['#fff']}-rgb),{m.group(1)})"
    return None


def block(css, selector):
    # The selector can appear in several rules; merge them in source order (later wins).
    bodies = re.findall(r"(?:^|[}\s])" + re.escape(selector) + r"\{([^{}]*)\}", css)
    if not bodies:
        sys.exit(f"selector not found: {selector}")
    merged = {}
    for b in bodies:
        merged.update(re.findall(r"(--[\w-]+)\s*:\s*([^;}]+)", b))
    return list(merged.items())


def overrides(decls, palette):
    out = []
    for name, value in decls:
        if ABSOLUTE.search(name):
            continue
        new = remap(value, palette)
        if new:
            out.append(f"{name}:{new}!important;")
    return out


def main():
    src = sys.argv[1]
    css = (urllib.request.urlopen(src).read().decode() if src.startswith("http")
           else Path(src).read_text())
    dark = overrides(block(css, ".theme-dark"), DARK)
    light = overrides(block(css, ".theme-light,:root"), LIGHT)
    shared = overrides(block(css, ".theme-dark,.theme-light,:root"), SHARED)

    def fmt(lines):
        return "\n".join("        " + l for l in lines)

    swift = f'''// GENERATED by tools/gen_theme.py from SoundCloud's app CSS. Do not edit by hand.
// SoundCloud theme variables remapped onto CloudPlayer's --cp-* tokens (filled in by Theme.swift).

enum ThemeVars {{
    static let css = """
    html body.theme-dark, html body.theme-dark [class*="theme-"] {{
{fmt(dark)}
    }}
    html body.theme-light, html body.theme-light [class*="theme-"] {{
{fmt(light)}
    }}
    html body, html body [class*="theme-"] {{
{fmt(shared)}
    }}
    """
}}
'''
    out = Path(__file__).resolve().parent.parent / "CloudPlayer" / "ThemeVars.swift"
    out.write_text(swift)
    print(f"wrote {out}: {len(dark)} dark, {len(light)} light, {len(shared)} shared overrides")


if __name__ == "__main__":
    main()
